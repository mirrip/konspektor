// Generates a Material 3 dark color scheme for Konspektor with Google's material-color-utilities.
import { argbFromHex, hexFromArgb, Hct, SchemeTonalSpot, MaterialDynamicColors } from "@material/material-color-utilities";

const seed = process.argv[2] || "#8B7CFF";
const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), true, 0.0);

const roles = [
  "primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
  "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
  "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
  "error", "onError", "errorContainer", "onErrorContainer",
  "background", "onBackground", "surface", "onSurface", "surfaceVariant", "onSurfaceVariant",
  "surfaceTint", "inverseSurface", "inverseOnSurface", "outline", "outlineVariant", "scrim",
  "surfaceBright", "surfaceDim", "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
  "surfaceContainerLow", "surfaceContainerLowest",
];

const mdc = typeof MaterialDynamicColors === "function" && !MaterialDynamicColors.primary
  ? new MaterialDynamicColors() : MaterialDynamicColors;

const lines = [];
for (const r of roles) {
  let dc = mdc[r];
  if (typeof dc === "function") dc = dc.call(mdc);
  if (!dc || typeof dc.getArgb !== "function") { console.error("missing role", r); continue; }
  const hex = hexFromArgb(dc.getArgb(scheme)).slice(1).toUpperCase();
  lines.push(`        ${r} = Color(0xFF${hex}),`);
}

console.log(`package app.konspektor.ui.theme

import androidx.compose.material3.darkColorScheme
import androidx.compose.ui.graphics.Color

/**
 * Dark color scheme generated by material-color-utilities (SchemeTonalSpot, seed ${seed}).
 * Regenerate: node gen.mjs "${seed}" > Color.kt
 */
val KonspektorDarkColors = darkColorScheme(
${lines.join("\n")}
)
`);
